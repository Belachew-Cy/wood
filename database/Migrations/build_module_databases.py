"""Split the one-file installation into one database per module.

The system used to keep everything in users.db, with finance.db and letter.db
already carved out. This tool takes a snapshot of those files, creates each
module file under database/, applies its schema file, and copies the rows in
with their ids, timestamps and history intact.

It is deliberately conservative:

* the legacy files are only ever read; nothing is dropped from them,
* every table is copied with its ids and checked against the source count,
* a shortfall or a mismatched column set stops the run before anything else is
  written, so a half-migrated installation is never reported as done.

Run it once, from the project root:

    python database/Migrations/build_module_databases.py

Re-running is safe: an existing file keeps its schema, and a table that already
holds the source's rows is left alone.
"""
from datetime import datetime
from pathlib import Path
import sqlite3
import sys


HERE = Path(__file__).resolve().parent
DATABASE_DIR = HERE.parent
PROJECT_DIR = DATABASE_DIR.parent
sys.path.insert(0, str(DATABASE_DIR))

import database_config as config  # noqa: E402


LEGACY_FILES = ("users.db", "finance.db", "letter.db")

TABLES_SQL = ("SELECT name FROM sqlite_master WHERE type = 'table'"
              " AND name NOT LIKE 'sqlite_%'")


def legacy_sources():
    """The old files that are present, as (label, path)."""
    found = []
    for name in LEGACY_FILES:
        path = PROJECT_DIR / name
        if path.exists() and path.stat().st_size:
            found.append((path.stem, path))
    return found


def back_up(sources, stamp):
    """Snapshot every legacy file before the first write."""
    config.BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    written = []
    for label, path in sources:
        target = config.BACKUP_DIR / "{}_{}.db".format(label, stamp)
        if target.exists():
            continue
        config.snapshot(path, target)
        written.append(target)
    return written


def source_for(table, sources):
    """The legacy file holding this table, or None."""
    for label, path in sources:
        conn = sqlite3.connect("file:{}?mode=ro".format(path.as_posix()), uri=True)
        try:
            found = conn.execute(
                "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?",
                (table,)).fetchone()
        finally:
            conn.close()
        if found:
            return label, path
    return None


def write_schemas(sources):
    """Rewrite schema_<module>.sql from the live legacy files.

    Only needed while the legacy files still exist; the generated files are what
    a fresh installation applies, and they are committed beside this script.
    """
    objects = {}
    for label, path in sources:
        conn = sqlite3.connect(str(path), timeout=15)
        try:
            for row in conn.execute(
                    "SELECT type, tbl_name, name, sql FROM sqlite_master"):
                if (row[3] and row[0] in ("table", "index", "trigger")
                        and not row[2].startswith("sqlite_")):
                    objects[(row[0], row[2])] = (row[1], row[3])
        finally:
            conn.close()

    for module in config.MODULES:
        key, schema = module["key"], module["schema"]
        lines = [
            "-- {} module ({})".format(module["label"], module["file"]),
            "-- {}".format(module["note"]),
            "-- Generated by Migrations/build_module_databases.py --refresh-schema;",
            "-- foreign keys into another module's file are dropped on purpose.",
            "",
        ]
        for table in module["tables"]:
            ddl = objects[("table", table)][1]
            lines.append(config.strip_foreign_keys(ddl, schema).strip() + ";")
            lines.append("")
        indexes = sorted(
            (module["tables"].index(tbl), name, sql)
            for (kind, name), (tbl, sql) in objects.items()
            if kind == "index" and tbl in module["tables"])
        for _order, _name, sql in indexes:
            lines.append(config.strip_foreign_keys(sql, schema).strip() + ";")
        lines.append("")
        for (kind, _name), (tbl, sql) in objects.items():
            if kind == "trigger" and tbl in module["tables"]:
                lines.append(sql.strip() + ";")
                lines.append("")
        (HERE / "schema_{}.sql".format(key)).write_text(
            "\n".join(lines), encoding="utf-8")


def columns(conn, table, schema="main"):
    return [(row[1], row[2], row[3], row[4], row[5]) for row in conn.execute(
        "PRAGMA {}.table_info({})".format(schema, table) if schema != "main"
        else "PRAGMA table_info({})".format(table))]


def create_module(module):
    """Create the file and apply its schema when it is not there yet."""
    path = config.module_path(module["key"])
    schema_file = HERE / "schema_{}.sql".format(module["key"])
    if not schema_file.exists():
        raise SystemExit("Missing schema file {}".format(schema_file))
    path.parent.mkdir(parents=True, exist_ok=True)
    fresh = not path.exists() or path.stat().st_size == 0
    conn = sqlite3.connect(str(path), timeout=15)
    try:
        conn.execute("PRAGMA journal_mode = WAL")
        if fresh:
            conn.executescript(schema_file.read_text(encoding="utf-8"))
            conn.commit()
    finally:
        conn.close()
    return fresh


def copy_module(module, sources):
    """Copy this module's rows out of the legacy files, ids and all."""
    path = config.module_path(module["key"])
    target = sqlite3.connect(str(path), timeout=15)
    target.execute("PRAGMA foreign_keys = ON")
    attached = []
    try:
        for label, source in sources:
            alias = "legacy_" + label
            # The source is only ever read here; the attach stays writable
            # because SQLite opens every attached file the same way.
            target.execute("ATTACH DATABASE ? AS {}".format(alias), (str(source),))
            attached.append(alias)

        report = []
        for table in module["tables"]:
            origin = source_for(table, sources)
            if origin is None:
                report.append((table, 0, 0, "no source"))
                continue
            label, _path = origin
            alias = "legacy_" + label
            source_columns = columns(target, table, alias)
            target_columns = columns(target, table, "main")
            if [row[0] for row in source_columns] != [row[0] for row in target_columns]:
                raise SystemExit(
                    "{}: the source and the new schema disagree on columns\n"
                    "  source: {}\n  target: {}".format(
                        table,
                        [row[0] for row in source_columns],
                        [row[0] for row in target_columns]))
            source_count = target.execute(
                'SELECT COUNT(*) FROM {}.{}'.format(alias, '"' + table + '"')
            ).fetchone()[0]
            present = target.execute(
                'SELECT COUNT(*) FROM "{}"'.format(table)).fetchone()[0]
            if present:
                if present != source_count:
                    raise SystemExit(
                        "{}: target already holds {} rows but the source has {};"
                        " resolve this by hand before migrating".format(
                            table, present, source_count))
                report.append((table, source_count, present, "already there"))
                continue
            names = ", ".join('"{}"'.format(row[0]) for row in target_columns)
            target.execute(
                'INSERT INTO "{}" ({}) SELECT {} FROM {}.{}'.format(
                    table, names, names, alias, '"' + table + '"'))
            copied = target.execute(
                'SELECT COUNT(*) FROM "{}"'.format(table)).fetchone()[0]
            if copied != source_count:
                raise SystemExit(
                    "{}: copied {} of {} rows".format(table, copied, source_count))
            report.append((table, source_count, copied, "copied"))
        target.commit()
        return report
    except Exception:
        target.rollback()
        raise
    finally:
        target.close()


def verify_module(module):
    """Integrity, column sets and every table's own count, in the new file."""
    path = config.module_path(module["key"])
    conn = sqlite3.connect(str(path), timeout=15)
    try:
        integrity = conn.execute("PRAGMA integrity_check").fetchone()[0]
        if integrity != "ok":
            raise SystemExit("{}: integrity_check said {}".format(path.name, integrity))
        problems = conn.execute("PRAGMA foreign_key_check").fetchall()
        if problems:
            raise SystemExit("{}: {} foreign key problem(s): {}".format(
                path.name, len(problems), problems[:5]))
        missing = [table for table in module["tables"] if not conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name = ?",
            (table,)).fetchone()]
        if missing:
            raise SystemExit("{}: missing table(s) {}".format(path.name, missing))
        return {table: conn.execute(
            'SELECT COUNT(*) FROM "{}"'.format(table)).fetchone()[0]
            for table in module["tables"]}
    finally:
        conn.close()


def main():
    sources = legacy_sources()
    if not sources:
        print("No legacy database files found in {}".format(PROJECT_DIR))
    if "--refresh-schema" in sys.argv:
        if not sources:
            raise SystemExit("--refresh-schema needs the legacy files")
        write_schemas(sources)
        print("Schema files rewritten from the legacy files.")
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    for target in back_up(sources, stamp):
        print("Backup written to {}".format(target))

    for module in config.MODULES:
        fresh = create_module(module)
        report = copy_module(module, sources) if sources else []
        counts = verify_module(module)
        path = config.module_path(module["key"])
        print("\n{} ({}){}".format(module["label"], path.name,
                                   "" if fresh else " [existing file]"))
        if report:
            for table, expected, actual, note in report:
                print("  {:<34} {:>5} / {:>5}  {}".format(
                    table, actual, expected, note))
        else:
            total = sum(counts.values())
            print("  {} table(s), {} row(s)".format(len(counts), total))

    print("\nEvery module file was created and verified against its source.")
    print("The legacy files in the project root were not modified.")


if __name__ == "__main__":
    main()
